import fs from "fs";
import path from "path";

// Load all parts
const initial = JSON.parse(fs.readFileSync("backend/src/services/skills/questionData.json", "utf-8"));
const part1 = JSON.parse(fs.readFileSync("backend/src/services/skills/questionData_part1.json", "utf-8"));
const part2 = JSON.parse(fs.readFileSync("backend/src/services/skills/questionData_part2.json", "utf-8"));
const part3 = JSON.parse(fs.readFileSync("backend/src/services/skills/questionData_part3.json", "utf-8"));
const part4 = JSON.parse(fs.readFileSync("backend/src/services/skills/questionData_part4.json", "utf-8"));
const part5 = JSON.parse(fs.readFileSync("backend/src/services/skills/questionData_part5.json", "utf-8"));

const skillMap = new Map();

// Helper to register
function register(list) {
  for (const s of list) {
    if (!skillMap.has(s.slug)) {
      skillMap.set(s.slug, s);
    }
  }
}

// Order of registration: initial (historical TS, Python, Smart Contracts, Dist Systems), then parts
register(initial);
register(part1);
register(part2);
register(part3);
register(part4);
register(part5);

const allSkills = Array.from(skillMap.values());
console.log(`Total assembled skills: ${allSkills.length}`);

// Validation
if (allSkills.length !== 83) {
  console.error(`ERROR: Expected exactly 83 skills, got ${allSkills.length}`);
  process.exit(1);
}

const questionIds = new Set();
let l1Count = 0;
let l2Count = 0;
let l3Count = 0;

for (const s of allSkills) {
  if (s.stages.length !== 3) {
    console.error(`ERROR: Skill ${s.slug} does not have 3 stages.`);
    process.exit(1);
  }
  for (const stage of s.stages) {
    if (stage.questions.length !== 1) {
      console.error(`ERROR: Skill ${s.slug} stage ${stage.level} has ${stage.questions.length} questions, expected 1.`);
      process.exit(1);
    }
    const q = stage.questions[0];
    if (questionIds.has(q.id)) {
      console.error(`ERROR: Duplicate question ID ${q.id}`);
      process.exit(1);
    }
    questionIds.add(q.id);
    if (stage.level === 1) l1Count++;
    if (stage.level === 2) l2Count++;
    if (stage.level === 3) l3Count++;

    if (!q.options || q.options.length !== 4) {
      console.error(`ERROR: Question ${q.id} does not have exactly 4 options.`);
      process.exit(1);
    }
    if (!q.correctOptionId || !["a", "b", "c", "d"].includes(q.correctOptionId)) {
      console.error(`ERROR: Question ${q.id} has invalid correctOptionId: ${q.correctOptionId}`);
      process.exit(1);
    }
    if (!q.prompt || q.prompt.trim().length === 0) {
      console.error(`ERROR: Question ${q.id} has empty prompt.`);
      process.exit(1);
    }
    if (!q.explanation || q.explanation.trim().length === 0) {
      console.error(`ERROR: Question ${q.id} has empty explanation.`);
      process.exit(1);
    }
  }
}

console.log(`Validation PASSED:`);
console.log(`- 83 Skills`);
console.log(`- ${l1Count} L1 Foundation Questions`);
console.log(`- ${l2Count} L2 Practitioner Questions`);
console.log(`- ${l3Count} L3 Advanced Questions`);
console.log(`- ${questionIds.size} Total Unique Questions`);

// Generate backend/src/services/skills/questionBanks.ts
const tsContent = `// Auto-generated by scripts/assemble_question_banks.mjs
// TrustToPay Demonstration Assessment Question Banks
// Total: 83 Skills, 249 Distinct Questions across Foundation, Practitioner, and Advanced levels.

import type { SeedSkillDefinition } from "./assessmentEngine.js";

export const DEMO_QUESTION_BANKS: SeedSkillDefinition[] = ${JSON.stringify(allSkills, null, 2)};
`;

fs.writeFileSync("backend/src/services/skills/questionBanks.ts", tsContent);
console.log("Wrote backend/src/services/skills/questionBanks.ts");

// JSON parts kept for verification
console.log("Assembly complete!");
